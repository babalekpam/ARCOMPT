export type AccountNature = "ACTIF" | "PASSIF" | "CHARGE" | "PRODUIT" | "MIXTE" | "ENGAGEMENT";

export function natureOfClass(cls: number): AccountNature {
  switch (cls) {
    case 1:
      return "PASSIF";
    case 2:
    case 3:
    case 5:
      return "ACTIF";
    case 4:
    case 8:
      return "MIXTE";
    case 6:
      return "CHARGE";
    case 7:
      return "PRODUIT";
    default:
      return "ENGAGEMENT";
  }
}

export interface ResolvedChartAccount extends ChartAccount {
  class: number;
  nature: AccountNature;
  postable: boolean;
  lettrable: boolean;
}

/** Résout le gabarit : un compte est imputable s'il n'a aucun sous-compte dans le gabarit. */
export function resolveChart(chart: ChartAccount[] = SYSCOHADA_CHART): ResolvedChartAccount[] {
  const numbers = chart.map((a) => a.number);
  return chart.map((a) => {
    const hasChild = numbers.some((n) => n !== a.number && n.startsWith(a.number));
    const lettrable = a.lettrable ?? numbers.some((n) => n !== a.number && a.number.startsWith(n) && chart.find((c) => c.number === n)?.lettrable === true);
    return {
      ...a,
      class: Number(a.number[0]),
      nature: natureOfClass(Number(a.number[0])),
      postable: !hasChild,
      lettrable,
    };
  });
}
